import { test, expect, type Locator } from '@playwright/test';

test('pointer and keyboard states across header, catalog, dialog, forms and simulator', async ({ page }) => {
  const inspect = async (element: Locator) => {
    await element.scrollIntoViewIfNeeded();
    const before = await element.boundingBox();
    await element.hover();
    // Inspect the pressed state without activating navigation/destructive/close actions.
    await page.evaluate(() => {
      const handler = (event: Event) => { event.preventDefault(); event.stopImmediatePropagation(); };
      (window as unknown as { stateInspectionHandler: EventListener }).stateInspectionHandler = handler;
      document.addEventListener('click', handler, true);
    });
    await page.mouse.down();
    const pointer = await element.evaluate(e => { const s = getComputedStyle(e); return { outline: s.outlineStyle, outlineColor: s.outlineColor, textEntry: e.matches('input,textarea,select'), shadow: s.boxShadow, border: s.borderColor }; });
    expect(pointer.outline).toBe('none');
    expect(pointer.shadow).toBe('none');
    expect(pointer.border).not.toBe('rgb(0, 0, 0)');
    await page.mouse.up();
    await page.evaluate(() => document.removeEventListener('click', (window as unknown as { stateInspectionHandler: EventListener }).stateInspectionHandler, true));
    await page.mouse.move(0, 0);
    if (await element.evaluate(e => e.tagName === 'SELECT')) await page.keyboard.press('Escape');
    await element.focus(); await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab');
    expect(await element.evaluate(e => getComputedStyle(e).outlineStyle)).toBe('solid');
    const after = await element.boundingBox();
    expect(Math.abs(before!.width - after!.width)).toBeLessThan(1);
    expect(Math.abs(before!.height - after!.height)).toBeLessThan(1);
  };
  await page.goto('/revestimentos');
  await inspect(page.getByRole('link', { name: /Minha seleção/ }).first());
  await inspect(page.getByRole('button', { name: 'Buscar', exact: true }));
  await inspect(page.getByLabel('Nome ou referência'));
  await inspect(page.getByLabel('Fabricante'));
  await inspect(page.getByLabel('Ordenar'));
  await inspect(page.getByRole('link', { name: 'Limpar filtros' }));
  await inspect(page.locator('.product-card a').first());
  await inspect(page.locator('.compare-check input').first());
  await inspect(page.locator('.card-actions .button').first());
  await page.getByRole('checkbox').first().check();
  await page.getByRole('button', { name: 'Abrir comparação' }).click();
  await inspect(page.getByRole('button', { name: 'Fechar comparação' }));
  await page.screenshot({ path: 'test-results/focus-dialog.png' });
  await page.keyboard.press('Escape');
  await page.goto('/revestimentos/classic-white-deco');
  await inspect(page.locator('.gallery-main'));
  await inspect(page.locator('.thumbnails button').first());
  expect(await page.locator('.thumbnails button').first().evaluate(e => getComputedStyle(e).borderColor)).toBe('rgb(64, 92, 83)');
  await inspect(page.locator('.technical-notes summary'));
  await page.locator('.gallery-main').click();
  await inspect(page.getByRole('button', { name: 'Fechar imagem' }));
  await page.keyboard.press('Escape');
  await page.goto('/simulador?produto=classic-white-deco');
  await inspect(page.getByRole('button', { name: 'Reiniciar estudo' }));
  await inspect(page.getByLabel('Material', { exact: true }));
  await inspect(page.getByLabel('Rotação limitada'));
  await inspect(page.getByRole('button', { name: 'Orientação: 0°' }));
  await inspect(page.getByRole('button', { name: 'Selecionar para orçamento', exact: true }));
  await page.getByRole('button', { name: 'Selecionar para orçamento', exact: true }).click();
  await page.goto('/orcamento');
  await inspect(page.getByRole('spinbutton'));
  await inspect(page.getByLabel('Notas para Classic White Deco (opcional)', { exact: true }));
  await inspect(page.getByLabel('Unidade de preferência'));
  await inspect(page.getByLabel('Resumo para copiar', { exact: true }));
  await inspect(page.getByRole('button', { name: 'Copiar resumo' }));
  await page.screenshot({ path: 'test-results/focus-form.png' });
  await page.goto('/lojas');
  await inspect(page.locator('.map-open').first());
  await page.locator('.map-open').first().click();
  await inspect(page.getByRole('dialog').getByRole('button'));
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await inspect(page.getByRole('button', { name: 'Menu', exact: true }));
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await inspect(page.getByRole('navigation', { name: 'Principal', exact: true }).getByRole('link').first());
  await page.screenshot({ path: 'test-results/focus-mobile-menu.png' });
});
